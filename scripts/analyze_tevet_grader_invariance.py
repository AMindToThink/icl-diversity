"""Grader-invariance analysis of D = C*a_n on the Tevet conTest datasets.

Question: is the metric a property of the text being scored, or of the grader
theta scoring it? For each conTest file (prompt_gen / resp_gen / story_gen)
and each grader run tag, per-sample D = C * a_n (per byte; the paper's primary
metric, derived exactly as in analyze_c_ainf.py, mean-of-ratios over the
per-permutation curves) is computed from the full .icl_curves sidecars, then:

  1. Per-grader Spearman rho between D and the human diversity label
     (label_value), on the common sample subset: does every grader see the
     signal the paper's grader sees?
  2. Pairwise Spearman between graders' per-sample D: do different-family,
     different-scale graders rank the same texts the same way?
  3. Two-way variance decomposition of the (item x grader) D matrix, raw and
     within-grader z-scored. Raw grader share includes each grader's absolute
     scale offset (GPT-2 is not on the same bits/byte scale as a 30B model);
     the z-scored view removes scale and location, leaving item share vs
     grader x item disagreement.

Sidecar discovery: each tag's conTest sidecars are searched first under this
repo's results/tevet/<tag>/, then under the main checkout's results/tevet/<tag>/
(the pre-existing qwen25_completion_v3 and qwen3_30b_a3b runs live there as
gitignored artifacts). The path used is recorded in the output JSON.

Outputs (results/tevet/grader_invariance/):
  invariance.json               full numbers
  generated_tables.md           markdown tables (spliced into FINDINGS.md)
  tevet_invariance_rho.tex      LaTeX table body for the paper
  tevet_invariance_macros.tex   \\newcommand macros for inline prose numbers

Usage:
  uv run python scripts/analyze_tevet_grader_invariance.py
  uv run python scripts/analyze_tevet_grader_invariance.py --tags qwen25_completion_v3 gpt2_completion
"""

