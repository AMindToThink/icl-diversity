"""Variance decomposition restricted to base-model-only grader subsets.

The published OLMo-matrix variance decomposition (`7_matrix_paper_outputs.py`,
`results/rlhf_experiment/matrix/FINDINGS.md`) uses two grader tiers: 5 graders
(Qwen2.5-3B + all four OLMo pipeline stages, including the aligned SFT/DPO/
Instruct stages) and 7 graders (+ Llama-3.1-8B, GPT-2). Both tiers include
graders that are either RLHF-aligned (OLMo-sft/dpo/instruct) or share a family
with generators sometimes graded by themselves. This script answers: does the
"generator stage dominates grader identity" finding survive when the grader
panel is restricted to unrelated *base* models only -- no OLMo self-scoring,
no Qwen (the cross-family model used to compute the paper's headline numbers
elsewhere), no aligned models at all?

Two grader tiers, both drawn from THETA_ROWS / EXTENDED_THETA_ROWS in
6_matrix_analysis.py / 7_matrix_paper_outputs.py (same JSONLs, same
diversity_score_D_C_an metric, no new scoring):

  PRIMARY (3 graders, no Qwen): GPT-2, Llama-3.1-8B, OLMo-2-7B base
  SUPPLEMENTARY (4 graders, +Qwen): GPT-2, Llama-3.1-8B, OLMo-2-7B base, Qwen2.5-3B

The generator-stage axis is untouched (still all 4 stages: base/sft/dpo/
instruct) -- only the grader (theta) axis is restricted.

Reuses the decomposition math and prompt-subset bookkeeping from
7_matrix_paper_outputs.py verbatim (two_way_decomposition,
three_way_decomposition, decompose_views, canonical_prompt_ids,
extended_row_missing, build_tensor) rather than reimplementing it. GPT-2's
1024-token context skips some AlpacaEval prompts (recorded in its
.skipped_context_overflow.json sidecar); the common prompt-feasible subset
across the included graders is used for every restricted tensor, exactly as
the published 7-grader decomposition does.

Sanity check (`--skip-sanity-check` to bypass): before trusting the restricted
runs, re-runs the *unmodified* published pipeline (7_matrix_paper_outputs.py's
`run()`) into a scratch directory and diffs every cell-mean / within-prompt
variance fraction against the committed
results/rlhf_experiment/matrix/variance_decomposition.json. A mismatch means
the input JSONLs have drifted since publication and the restricted-grader
numbers below should not be trusted either.

Outputs (does NOT touch the published FINDINGS.md, variance_decomposition.json,
or olmo_matrix_variance.tex):
  results/rlhf_experiment/matrix/variance_base_graders.json
  results/rlhf_experiment/matrix/variance_base_graders.md

Usage:
  uv run python scripts/rlhf_experiment/8_variance_base_graders.py
  uv run python scripts/rlhf_experiment/8_variance_base_graders.py --skip-sanity-check
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import tempfile
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[2]
MATRIX_DIR = REPO_ROOT / "results" / "rlhf_experiment" / "matrix"


def _load_module(path: Path, name: str):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


MPO = _load_module(Path(__file__).with_name("7_matrix_paper_outputs.py"), "matrix_paper_outputs_mod8")
MA = MPO.MA

PRIMARY_LABELS = ["GPT-2", "Llama-3.1-8B", "OLMo-base"]
SUPPLEMENTARY_LABELS = ["GPT-2", "Llama-3.1-8B", "OLMo-base", "Qwen-3B"]

# Every grader row this script can possibly draw from (label -> (model_id, path)).
ALL_ROWS = {label: (model_id, path) for label, model_id, path in list(MA.THETA_ROWS) + MPO.EXTENDED_THETA_ROWS}
for _labels in (PRIMARY_LABELS, SUPPLEMENTARY_LABELS):
    _unknown = set(_labels) - set(ALL_ROWS)
    if _unknown:
        raise ValueError(f"unknown grader labels {_unknown}; known: {sorted(ALL_ROWS)}")

GENERATED_BY = "Auto-generated by scripts/rlhf_experiment/8_variance_base_graders.py -- do not hand-edit."

# Tolerance for the sanity-check comparison against the committed JSON.
_RTOL, _ATOL = 1e-9, 1e-12


# ---------------------------------------------------------------------------
# Sanity check: unmodified published pipeline must reproduce committed numbers
# ---------------------------------------------------------------------------

def sanity_check() -> dict:
    """Re-run 7_matrix_paper_outputs.py's unmodified pipeline into a scratch dir
    and diff every reported variance fraction against the committed
    variance_decomposition.json. Raises if anything drifted."""
    published_path = MATRIX_DIR / "variance_decomposition.json"
    if not published_path.exists():
        raise FileNotFoundError(
            f"{published_path} missing; run 7_matrix_paper_outputs.py first"
        )
    published = json.loads(published_path.read_text())

    with tempfile.TemporaryDirectory(prefix="variance_sanity_") as tmp:
        recomputed = MPO.run(Path(tmp), update_findings=False)

    mismatches: list[dict] = []

    def cmp(path_label: str, pub: dict, got: dict) -> None:
        for k in pub:
            if not np.isclose(pub[k], got[k], rtol=_RTOL, atol=_ATOL):
                mismatches.append({"where": path_label, "key": k, "published": pub[k], "recomputed": got[k]})

    for pset in MA.PROMPT_SETS:
        p_ps, r_ps = published["prompt_sets"][pset], recomputed["prompt_sets"][pset]
        for level in ("cell_means_all_graders", "cell_means_olmo_only"):
            cmp(f"{pset}.{level}.frac", p_ps[level]["frac"], r_ps[level]["frac"])
        for level in ("per_prompt_all_graders", "per_prompt_olmo_only"):
            cmp(f"{pset}.{level}.within_prompt_frac", p_ps[level]["within_prompt_frac"], r_ps[level]["within_prompt_frac"])
        p_ext, r_ext = published["extended"][pset]["all_graders_common"], recomputed["extended"][pset]["all_graders_common"]
        cmp(f"{pset}.extended.all_graders_common.cell_means.frac", p_ext["cell_means"]["frac"], r_ext["cell_means"]["frac"])
        cmp(f"{pset}.extended.all_graders_common.per_prompt.within_prompt_frac",
            p_ext["per_prompt"]["within_prompt_frac"], r_ext["per_prompt"]["within_prompt_frac"])
        if published["extended"][pset]["n_prompts_common"] != recomputed["extended"][pset]["n_prompts_common"]:
            mismatches.append({
                "where": f"{pset}.extended.n_prompts_common",
                "key": "n",
                "published": published["extended"][pset]["n_prompts_common"],
                "recomputed": recomputed["extended"][pset]["n_prompts_common"],
            })

    return {"ok": not mismatches, "mismatches": mismatches, "published_path": str(published_path.relative_to(REPO_ROOT))}


# ---------------------------------------------------------------------------
# Restricted-grader decomposition
# ---------------------------------------------------------------------------

def restricted_dropped(theta_cells: dict, canonical: set[str], pset: str) -> dict[str, set[str]]:
    """Per-grader dropped-prompt sets for every extended (non-pre-registered)
    row this script might use (Llama, GPT-2). Pre-registered rows (OLMo-base,
    Qwen-3B) are, by construction of `canonical`, complete -- empty set."""
    dropped: dict[str, set[str]] = {label: set() for label in ALL_ROWS}
    for label, (_mid, path) in ALL_ROWS.items():
        if label not in MPO.EXTENDED_LABELS:
            continue
        dropped[label] = MPO.extended_row_missing(theta_cells, label, path, canonical, pset)
    return dropped


def decompose_for_labels(
    theta_cells: dict, pset: str, labels: list[str], canonical: set[str], dropped: dict[str, set[str]]
) -> dict:
    dropped_union: set[str] = set()
    for label in labels:
        dropped_union |= dropped[label]
    common = sorted(canonical - dropped_union)
    if len(common) < 30:
        raise ValueError(
            f"prompt intersection for graders {labels} on {pset} is unexpectedly small "
            f"({len(common)} < 30); refusing to proceed with a near-empty subset"
        )
    X = MPO.build_tensor(theta_cells, pset, labels, common)
    view = MPO.decompose_views(X, labels)
    view["dropped_prompts_by_grader"] = {label: sorted(dropped[label]) for label in labels}
    return view


def run() -> dict:
    theta_cells = MPO.load_theta_cells(list(MA.THETA_ROWS) + MPO.EXTENDED_THETA_ROWS)

    out: dict = {
        "generated_by": "scripts/rlhf_experiment/8_variance_base_graders.py",
        "command": "uv run python scripts/rlhf_experiment/8_variance_base_graders.py",
        "metric_key": "diversity_score_D_C_an",
        "gen_order": list(MA.GEN_ORDER),
        "tiers": {
            "primary": {"labels": PRIMARY_LABELS, "description": "3 graders, no Qwen, all base models"},
            "supplementary": {"labels": SUPPLEMENTARY_LABELS, "description": "4 graders, +Qwen, all base models"},
        },
        "prompt_sets": {},
    }

    for pset in MA.PROMPT_SETS:
        canonical = MPO.canonical_prompt_ids(theta_cells, pset)
        dropped = restricted_dropped(theta_cells, canonical, pset)
        pset_out: dict = {
            "n_prompts_canonical": len(canonical),
            "dropped_n": {label: len(ids) for label, ids in dropped.items()},
        }
        for tier_name, labels in (("primary", PRIMARY_LABELS), ("supplementary", SUPPLEMENTARY_LABELS)):
            pset_out[tier_name] = decompose_for_labels(theta_cells, pset, labels, canonical, dropped)
        out["prompt_sets"][pset] = pset_out

    return out


# ---------------------------------------------------------------------------
# Emitters
# ---------------------------------------------------------------------------

def pct1(frac: float) -> str:
    return f"{100 * frac:.1f}"


def emit_markdown(out: dict, sanity: dict) -> str:
    lines = [
        f"<!-- {GENERATED_BY} -->",
        "",
        "# Variance decomposition, base-model-only grader subsets",
        "",
        "Companion to `results/rlhf_experiment/matrix/FINDINGS.md`'s variance",
        "decomposition, restricted to grader panels with no OLMo self-scoring, no",
        "aligned graders, and (primary tier) no Qwen.",
        "",
        "Sanity check (re-running the unmodified published pipeline into a scratch",
        f"dir and diffing against `{sanity['published_path']}`): "
        + ("**PASS** -- every fraction matched." if sanity["ok"] else "**FAIL** -- see mismatches below."),
        "",
    ]
    if not sanity["ok"]:
        lines.append("```")
        lines.append(json.dumps(sanity["mismatches"], indent=2))
        lines.append("```")
        lines.append("")

    for tier_name, tier in out["tiers"].items():
        lines.append(f"## {tier_name.capitalize()} tier: {', '.join(tier['labels'])}")
        lines.append("")
        lines.append(f"({tier['description']})")
        lines.append("")
        lines.append(
            "| Variance source | AlpacaEval cell means | AlpacaEval within-prompt "
            "| NB cell means | NB within-prompt |"
        )
        lines.append("|---|---|---|---|---|")
        for display, key in [
            ("Generator stage", "stage"),
            ("Grader θ", "grader"),
            ("Grader × stage interaction", "interaction"),
        ]:
            cells = []
            for pset in MA.PROMPT_SETS:
                view = out["prompt_sets"][pset][tier_name]
                cells.append(pct1(view["cell_means"]["frac"][key]) + "%")
                cells.append(pct1(view["per_prompt"]["within_prompt_frac"][key]) + "%")
            lines.append(f"| {display} | " + " | ".join(cells) + " |")
        n_alpaca = out["prompt_sets"]["alpacaeval"][tier_name]["n_prompts"]
        n_nb = out["prompt_sets"]["nbcurated"][tier_name]["n_prompts"]
        lines.append("")
        lines.append(f"n prompts: AlpacaEval={n_alpaca}, NoveltyBench={n_nb}")
        lines.append("")

    lines.append("## Reproduce")
    lines.append("")
    lines.append("```bash")
    lines.append(out["command"])
    lines.append("```")
    lines.append("")
    lines.append("Full numbers: `variance_base_graders.json` (this directory).")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--skip-sanity-check", action="store_true",
                     help="skip re-running the published pipeline to verify it still reproduces "
                          "the committed variance_decomposition.json (default: run it)")
    args = ap.parse_args()

    if args.skip_sanity_check:
        sanity = {"ok": None, "mismatches": [], "published_path": "SKIPPED", "skipped": True}
    else:
        sanity = sanity_check()
        if not sanity["ok"]:
            raise AssertionError(
                "sanity check FAILED: recomputing the published pipeline does not reproduce "
                f"the committed variance_decomposition.json ({len(sanity['mismatches'])} mismatches); "
                "the restricted-grader numbers below cannot be trusted until this is resolved. "
                f"Mismatches: {sanity['mismatches'][:5]}"
            )

    out = run()
    out["sanity_check"] = sanity

    MATRIX_DIR.mkdir(parents=True, exist_ok=True)
    (MATRIX_DIR / "variance_base_graders.json").write_text(json.dumps(out, indent=2))
    (MATRIX_DIR / "variance_base_graders.md").write_text(emit_markdown(out, sanity))

    print(f"sanity check: {'PASS' if sanity['ok'] else ('SKIPPED' if sanity.get('skipped') else 'FAIL')}")
    for pset in MA.PROMPT_SETS:
        for tier_name in ("primary", "supplementary"):
            view = out["prompt_sets"][pset][tier_name]
            cm = view["cell_means"]["frac"]
            wp = view["per_prompt"]["within_prompt_frac"]
            print(
                f"[{pset}][{tier_name}] n={view['n_prompts']} cell-means: stage {100*cm['stage']:.1f}% "
                f"/ grader {100*cm['grader']:.1f}% / interaction {100*cm['interaction']:.1f}%   "
                f"within-prompt: stage {100*wp['stage']:.1f}% / grader {100*wp['grader']:.1f}% "
                f"/ interaction {100*wp['interaction']:.1f}%"
            )
    print(f"\nwrote {MATRIX_DIR / 'variance_base_graders.json'}")
    print(f"wrote {MATRIX_DIR / 'variance_base_graders.md'}")


if __name__ == "__main__":
    main()
